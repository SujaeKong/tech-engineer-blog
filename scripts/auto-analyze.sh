#!/bin/bash
# 매일 7:30 crontab에서 실행되는 자동 분석 스크립트
# 1) git pull (GitHub Actions가 수집한 최신 데이터)
# 2) Claude Code로 분석 + 포스트 생성
# 3) 커밋 + 푸시
# 4) 링크수정 + 카페게시는 push 이후 GitHub Actions(cafe-post.yml)가 전담
#    → 로컬/웹 어디서 돌리든 카페 게시는 CI 단일 경로로만 일어난다 (이중 게시 방지)

# 개별 실패가 전체를 중단하지 않도록 set -e 사용 안 함

# 스크립트 자기 위치(scripts/) 기준으로 리포 루트를 계산 → 어디에 clone하든 동작
BLOG_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOG_FILE="$HOME/.tech-engineer-blog-auto.log"

# crontab 환경에서 PATH 설정
export PATH="$HOME/.nvm/versions/node/v22.17.0/bin:/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:$PATH"

echo "===== $(date '+%Y-%m-%d %H:%M:%S') 자동 분석 시작 =====" >> "$LOG_FILE"

cd "$BLOG_DIR"

# 로컬 변경사항 초기화 후 pull (로그파일은 리포 밖이므로 안전)
git checkout -- . >> "$LOG_FILE" 2>&1 || true
git clean -fd >> "$LOG_FILE" 2>&1 || true
git pull >> "$LOG_FILE" 2>&1

# Claude Code로 분석 및 포스트 생성
echo "$(date '+%Y-%m-%d %H:%M:%S') Claude 분석 시작..." >> "$LOG_FILE"
cat <<'PROMPT' | claude -p --allowedTools "Read Write Edit Glob Grep Bash(git:*) Bash(ls:*)" >> "$LOG_FILE" 2>&1
_data/news_raw.json 파일을 읽고, 기술사 출제분야 8개 카테고리(소프트웨어공학/데이터베이스/네트워크/정보보안/IT경영/시스템구조/AI데이터분석/신기술융합) 관점에서 의미있는 뉴스를 선별하여 토픽 분석 포스트를 작성해줘.

**뉴스 선별 기준 (엄격하게 적용)**:
- ✅ 채택: 정부/공공기관 정책·표준 발표, 국제 표준 제정, 보안 사고/취약점, 신기술 출시, 학술 연구 성과, 기업의 의미있는 기술 발표
- ❌ 제외: 단순 칼럼/오피니언, 업체 홍보·마케팅 자료, 브랜드평판/순위 기사, 일반 비즈니스 팁, 단일 출처의 칼럼성 글
- 한 토픽이 **여러 출처에서 다뤄지는 뉴스**일수록 우선순위 높음 (실제 사건성)
- 단일 칼럼·홍보 글은 토픽으로 채택하지 말 것

작성 기준의 원본은 CLAUDE.md의 「포스트 작성 규칙」이다. 아래와 다르면 CLAUDE.md를 따른다.

**목적**: 뉴스 소개가 아니라, 수험생(직장인)이 서브노트로 그대로 옮겨 쓸 수 있는 답안 재료를 주는 글.

포스트는 3개 작성하되, 3개 모두 다른 카테고리로 작성해줘. 3개 모두 아래 품질 기준을 충족해야 한다.
배치에 쓸 만한 기사가 3개 미만이면 억지로 채우지 말고, 3번째는 출제 예상 토픽을 깊게 다루는 '토픽 심화 글'로 써줘
(뉴스 요약 섹션에는 배치 내 관련 최근 동향을 인용).

카테고리 선택 시 _data/exam_category_analysis.json의 기출 비중을 참고하고, 기존 _posts/ 폴더에서 최근 33개 포스트의 카테고리 분포와 카테고리별 마지막 작성일을 확인해서 기출 비중 대비 부족하거나 오래 쓰지 않은 카테고리를 우선 선택해줘.
기출 비중: 시스템구조 19% > AI데이터분석 19% > IT경영 10% > 소프트웨어공학 8% > 정보보안 8% > 네트워크 6% > 신기술융합 4% > 데이터베이스 2%

각 포스트는 _posts/ 폴더에 YYYY-MM-DD-제목.md 형식으로 생성해줘(날짜는 KST 기준). 이미 _posts/에 있는 포스트와 중복되는 주제는 제외해줘.
제목은 30자 내외로 핵심만 쓰고, "~시스템 아키텍처/체계" 같은 접미사를 기계적으로 붙이지 마. 파일명에 + . [ ] 한자 등 특수문자 금지.

**본문 구조 (섹션 제목 고정 — 카페 게시 스크립트가 '뉴스 요약'·'출제 포인트' 문자열로 파싱하므로 바꾸지 마)**:
1. ## 1. 뉴스 요약 — 3~5문장. 매체명·보도일은 news_raw.json의 source/pub_date를 그대로 써줘(포스트 작성일을 보도일처럼 쓰지 마). 여러 매체가 다뤘으면 "OO·OO 등(MM-DD)".
2. ## 2. 핵심 개념 — 답안 첫 줄로 쓸 수 있는 정의(1~2문장), ASCII 코드블록 구성도 1개 이상, 6행 이상 비교표, 확실한 관련 표준·법령·수치 기준.
3. ## 3. 기술사 출제 포인트 — "- " 불릿 8~12개, 키워드형. 상위 4개만 카페에 나가므로 가장 중요한 것을 먼저. 25점 단답/논술 같은 문제 유형 분류는 하지 마.
   올바른 예: - 개념 정의와 필요성 / - 기존 방식과의 비교 / - 아키텍처 구성요소 / - 도입 시 고려사항
   잘못된 예: - 25점 단답/약술: xxx를 설명하시오
4. ## 4. 연결 기출 토픽과 예상 변형 — 이어지는 기출 빈출 토픽과 변형 출제 가능성. 기출 회차는 _data/exam_trend_integrated.json·139/140회 분석 포스트로 확인 가능한 것만 쓰고, 아니면 회차 없이 "빈출 토픽"으로만.
5. ## 5. 답안 구성 예시 — 단답형(정의·특징 3개·구성도 키워드)과 논술형 목차(개요 → 구성/비교 → 적용방안 → 고려사항 → 기술사 제언).
6. ## 6. 관련 토픽 연계 — 내부 링크 3~5개.
7. 마지막 줄: **암기 키워드**: A · B · C …

**품질 기준**:
- 본문 2,500자 이상(공백 제외). 짧으면 구성도·비교표·고려사항부터 보강.
- 상투구 금지: "핵심은 ~이다. ① ② ③ ④ … 관건은 ~다", "~영역과 직결된다"를 매 글 반복하지 말고 주제에 맞게 문장 구조를 바꿔.
- 사실 생성 금지: 기사가 제목만 있으면 제목에 없는 수치·기관 세부사항을 지어내지 말고, 일반 기술 개념은 개념으로 서술.

중요: categories는 8개 중 1개만 넣어줘. 복수 카테고리 금지.
올바른 예: categories: 정보보안
잘못된 예: categories: [정보보안, IT경영]

중요: frontmatter에 검색 노출용 description을 한 줄 넣어줘(구글 검색 스니펫으로 쓰임).
- 형식: description: "<한 문장, 100~150자>"
- 핵심 개념 키워드 2~3개와 해당 카테고리, 그리고 '정보관리기술사'를 자연스럽게 포함.
- 날짜/출처("2026-..-.. OO일보")로 시작하지 말고 주제·개념 중심으로 작성.
- 예: description: "네이버 실행형 AI(Agentic AI) 공개. 에이전트 구성요소·오케스트레이션·안전장치를 정보관리기술사 소프트웨어공학 관점에서 정리한다."

중요: 마크다운 표 작성 시 반드시 표 위에 빈 줄을 넣고, 표 내부 행 사이에는 빈 줄을 넣지 마.

중요: 관련 토픽 연계에서 다른 포스트 링크는 반드시 Jekyll URL 형식으로 작성해. 파일명(.md)을 그대로 쓰면 404 발생.
올바른 예: [제목](/tech-engineer-blog/posts/제목-슬러그/)
잘못된 예: [제목](2026-05-06-제목-슬러그.md)

완료 후, 오늘 작성한 포스트 중 다음 회차 정보관리기술사 시험에 출제될 확률이 가장 높은 토픽 1개를 선정해서 _data/today_topic.txt 파일에 해당 포스트의 파일명(예: 2026-03-31-제목.md)만 한 줄로 저장해줘.

**오늘의 토픽 선정 기준** (고정된 카테고리 순서로 정하지 말고, 3편 중 가장 좋은 1편을 고를 것):
1. 시험 출제 가능성 - 기술사 출제분야와의 연관성, 최근 기출 트렌드
2. 답안 활용도 - 구성도·비교표·기출 연결이 가장 충실한 글
3. 뉴스의 실제성 - 사건/표준/정책 발표 등 구체적 이벤트 (단순 칼럼/홍보 X)
4. 출처 다양성 - 여러 언론사가 다룬 토픽 우선
5. 시사성 - 최근 1-2주 내 이슈

커밋 전에 확인해줘: 내부 링크가 모두 실제 포스트를 가리키는지, 표 위 빈 줄, 글당 2,500자 이상, 상투구 반복 여부.
그 다음 git add, commit, push까지 해줘. 커밋 메시지에 오늘의 토픽 선정 이유를 한 줄로 적어줘.
